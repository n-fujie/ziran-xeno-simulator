// Regenerates docs/benchmark-results.md from a live run of all three benchmark suites.
// Usage: node scripts/benchmark-results.ts   (deterministic; no timestamps other than the generation date line)
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ensurePresets } from '../src/presets/index.ts';
import { runBenchmark } from '../src/bench/layers.ts';
import { runTheoryBenchmarks } from '../src/bench/theory.ts';
import { runMetaBenchmarks } from '../src/bench/meta.ts';
import { ENGINE_VERSION } from '../src/core/engine.ts';

ensurePresets();
const esc = (s: unknown) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const L = runBenchmark(), T = runTheoryBenchmarks(), M = runMetaBenchmarks();
const nChecks = L.reduce((a, l) => a + l.checks.length, 0), nFail = L.reduce((a, l) => a + l.checks.filter((c) => !c.pass).length, 0);
const o: string[] = [];
o.push('# Benchmark results (generated)', '',
  `Generated by \`node scripts/benchmark-results.ts\` · engine ${ENGINE_VERSION} · Node ${process.version}.`, '',
  'All results below are **synthetic**. None of the three suites is empirical validation. See [BENCHMARKS.md](../BENCHMARKS.md) for what each suite is for.', '',
  '## Implementation Conformance Benchmarks', '', `Claim status: **implementation property**. ${nChecks} checks, ${nFail} failed.`, '',
  '| layer | title | status | checks | failed |', '|---|---|---|---|---|',
  ...L.map((l) => `| ${l.layer} | ${esc(l.title)} | ${l.status} | ${l.checks.length} | ${l.checks.filter((c) => !c.pass).length} |`), '');
o.push('## Theory-Discriminating Benchmarks (A–N)', '',
  `${T.length} benchmarks: ${['positive', 'negative', 'null'].map((k) => `${T.filter((r) => r.outcomeType === k).length} ${k}`).join(', ')}. "Positive" means the expected distinction appeared in this synthetic world; "negative" means the favoured Ziran / Xeno mechanism did not win or produced no benefit; "null" means no distinction either way.`, '',
  '| id | kind | outcome | claim status | actual result |', '|---|---|---|---|---|',
  ...T.map((r) => `| ${r.id} | ${r.definition?.kind ?? ''} | **${r.outcomeType}** | ${r.claimStatus} | ${esc(r.verdict)} |`), '');
for (const r of T) {
  const d = r.definition;
  o.push(`### ${r.id} — ${esc(r.title)}`, '', `- **Question:** ${esc(r.question)}`,
    `- **Hypothesis / expected distinction:** ${r.hypothesis === null ? 'none predefined (no winner stated in advance)' : esc(r.hypothesis)}`,
    `- **Setup:** ${esc(d?.initialConfiguration)}; perturbation: ${esc(d?.perturbation)}`,
    `- **Compared models:** ${esc((d?.modelClasses ?? r.modelClasses).join(' · '))}`,
    `- **Measured outputs:** ${esc(d?.measuredOutcomes.join('; '))}`,
    `- **Predicate:** \`${esc(d?.successPredicate)}\``,
    `- **What would count as failure:** ${esc(d?.counterEvidence)}`,
    `- **Uncertainty:** ${esc(d?.uncertainty)}`,
    `- **Actual result:** ${esc(r.verdict)} — hypothesis ${r.hypothesis === null ? 'n/a' : r.hypothesisHolds ? 'holds here' : 'does not hold here'}; outcome **${r.outcomeType}**`,
    `- **Claim status:** ${r.claimStatus} · evidence: ${r.evidence}`, '');
}
o.push('## Meta-Boundedness Benchmarks (MB1–MB7)', '',
  `${M.length} benchmarks: ${M.filter((r) => r.stableOverall).length} stable, ${M.filter((r) => !r.stableOverall && !r.error).length} meta-dependent, ${M.filter((r) => r.error).length} errors. Claim status of all: **synthetic-world result**.`, '');
for (const r of M) {
  const d = r.definition;
  o.push(`### ${r.id} — ${esc(r.question)}`, '',
    `- **Result under test:** ${esc(r.result)}`,
    `- **Expected distinction:** ${d?.expected ? esc(d.expected) : 'none predefined'}`,
    `- **Setup:** ${esc(d?.setup)}`, `- **Compared meta-configurations:** ${esc(d?.compared.join(' · '))}`,
    `- **Measured outputs:** ${esc(d?.measured)}`, `- **Stability predicate:** \`${esc(d?.stabilityPredicate)}\``,
    `- **What would count as failure:** ${esc(d?.counterEvidence)}`,
    `- **Actual result:** ${esc(r.statement)}`,
    `- **Perturbations:** ${r.perturbations.filter((p) => p.stable).length} stable / ${r.perturbations.filter((p) => !p.stable).length} changed`,
    `- **Claim status:** ${r.claimStatus}`, '');
}
const out = fileURLToPath(new URL('../docs/benchmark-results.md', import.meta.url));
mkdirSync(fileURLToPath(new URL('../docs', import.meta.url)), { recursive: true });
writeFileSync(out, o.join('\n'));
console.log(`wrote docs/benchmark-results.md — ${nChecks} conformance checks (${nFail} failed), ${T.length} theory, ${M.length} meta`);
process.exitCode = nFail || T.some((r) => r.error) || M.some((r) => r.error) ? 1 : 0;
